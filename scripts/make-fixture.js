// Δημιουργεί ένα ΣΥΝΘΕΤΙΚΟ αρχείο FID στη μορφή εξαγωγής του Quantum Music Studio (pundora-fid-v3),
// με τη δική μας μηχανή, για τον έλεγχο της εισαγωγής. Δεν περιέχει δεδομένα του Studio.
const E = require('../src/engine.js'), fs = require('fs'), path = require('path');
const prep = E.prepare(0, 0.5), W = 400, N = 2048;
const A = E.toAudio({ J: 7, nu0: 3, nu1: 0, T2: 0.25, T2s: 0.04, T1: 1, tau: 0.1, echo: true, S: 1 });
const t = [], q = [[[], []], [[], []]];
for (let i = 0; i < N; i++) { const tm = i * W / (N - 1); t.push(tm); for (const k of [0, 1]) { const s = E.signalAt(prep, A, k, tm / 1000); q[k][0].push(s.re); q[k][1].push(s.im); } }
const out = { format: 'pundora-fid-v3', model: 'nmr', source: 'Synthetic fixture generated by spin-ladder-synth (not Studio data)', physicalWindowMs: W,
  audioDurationSeconds: 8, carrierHz: [258.6525475130918, 387.54094239104757], referenceA4Hz: 435, observed: 'both',
  timeMs: t, q0Re: q[0][0], q0Im: q[0][1], q1Re: q[1][0], q1Im: q[1][1] };
fs.writeFileSync(path.join(__dirname, '..', 'test', 'fixtures', 'synthetic-fid.json'), JSON.stringify(out));
console.log('fixture written');
